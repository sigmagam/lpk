export default function HostedByBadge() {
  const marqueeRef = useRef<HTMLUListElement>(null);

  useEffect(() => {
    const ul = marqueeRef.current;
    if (!ul) return;

    const handlePageShow = (event: PageTransitionEvent) => {
      // Page was restored from the back/forward cache: the marquee may come
      // back frozen, so restart the animation to guarantee it scrolls again.
      if (!event.persisted) return;
      ul.classList.remove("animate-marquee");
      void ul.offsetWidth; // force reflow so the restart actually applies
      ul.classList.add("animate-marquee");
    };

    window.addEventListener("pageshow", handlePageShow);
    return () => window.removeEventListener("pageshow", handlePageShow);
  }, []);

  // Duplicated so the marquee can loop seamlessly while scrolling right.
  const loop = [...providers, ...providers];

  return (
    <div className="mt-10 flex flex-col items-center gap-4">
      <div className="inline-flex items-center gap-2.5 rounded-full border border-navy-800 bg-navy-900/60 px-5 py-2.5 backdrop-blur-sm">
        <span className="inline-flex items-center gap-2 text-[11px] font-bold uppercase tracking-wider text-slate-500">
          <Server className="h-4 w-4" aria-hidden="true" />
          Hosted by
        </span>
      </div>

      <div
        className="relative w-full max-w-2xl overflow-hidden"
        style={{
          maskImage:
            "linear-gradient(to right, transparent, black 12%, black 88%, transparent)",
          WebkitMaskImage:
            "linear-gradient(to right, transparent, black 12%, black 88%, transparent)",
        }}
      >
        <ul
          ref={marqueeRef}
          className="flex w-max animate-marquee items-center gap-x-4 will-change-transform motion-reduce:animate-none"
        >
          {loop.map((provider, index) => (
            <li key={`${provider.name}-${index}`} className="shrink-0">
              <a
                href={provider.url}
                target="_blank"
                rel="noopener noreferrer"
                aria-label={provider.name}
                title={provider.name}
                className="group inline-flex items-center gap-2 whitespace-nowrap rounded-full border border-navy-800 bg-navy-900/40 px-3.5 py-2 text-slate-300 transition-colors hover:border-navy-600 hover:bg-navy-800/60 hover:text-white focus:outline-none focus-visible:ring-2 focus-visible:ring-white/40 focus-visible:ring-offset-2 focus-visible:ring-offset-navy-950"
              >
                <svg
                  role="img"
                  viewBox="0 0 24 24"
                  style={{ color: provider.color }}
                  className="h-6 w-6 shrink-0 fill-current"
                  aria-hidden="true"
                >
                  <path d={provider.path} />
                </svg>
                <span className="text-sm font-semibold">{provider.name}</span>
              </a>
            </li>
          ))}
        </ul>
      </div>
    </div>
  );
}
